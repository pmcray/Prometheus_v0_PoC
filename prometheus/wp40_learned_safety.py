# LearnedSafetyCRLS — TransformerCRLS + WP40 learned safety gate
# ---------------------------------------------------------------------------

class LearnedSafetyCRLS(TransformerCRLS):
    """
    WP40 upgrade of TransformerCRLS: adds a learned safety gate.

    Parameters
    ----------
    (all TransformerCRLS parameters, plus:)
    safety_d_hidden : int          Hidden size of safety classifier (default 16).
    safety_lr : float              Classifier learning rate (default 0.05).
    safety_l2 : float              Classifier L2 (default 1e-4).
    safety_threshold : float       Min P(safe) to allow action (default 0.60).
    safety_abstain_threshold : float  Confidence abstain threshold (default 0.30).
    safety_min_train_samples : int  Min samples before classifier is used (default 20).
    safety_batch_size : int        Training batch size (default 8).
    safety_fallback : SynthesisAction  Fallback action when blocked (default RESET_UNIFORM).
    safety_seed : int
    """

    def __init__(
        self,
        strategies:                  List[str],
        # WP40-specific
        safety_d_hidden:             int   = 16,
        safety_lr:                   float = 0.05,
        safety_l2:                   float = 1e-4,
        safety_threshold:            float = 0.60,
        safety_abstain_threshold:    float = 0.30,
        safety_min_train_samples:    int   = 20,
        safety_batch_size:           int   = 8,
        safety_fallback:             SynthesisAction = SynthesisAction.RESET_UNIFORM,
        safety_seed:                 int   = 0,
        # TransformerCRLS pass-through
        invariant_registry:          Optional[InvariantRegistry] = None,
        **kwargs: Any,
    ):
        super().__init__(
            strategies          = strategies,
            invariant_registry  = invariant_registry,
            **kwargs,
        )

        n_actions = len(SynthesisAction)
        d_state   = 8

        self._safety_classifier = SafetyClassifier(
            d_state   = d_state,
            n_actions = n_actions,
            d_hidden  = safety_d_hidden,
            lr        = safety_lr,
            l2        = safety_l2,
            seed      = safety_seed,
        )
        self._safety_dataset = SafetyDataset(n_actions=n_actions)
        self._safety_batch_size = safety_batch_size
        self._safety_fallback   = safety_fallback

        # Build fallback WP27 InvariantGuard
        registry = invariant_registry or make_default_registry()
        self._wp27_guard = InvariantGuard(registry=registry)
        self._learned_guard = LearnedSafetyGuard(
            classifier        = self._safety_classifier,
            fallback_guard    = self._wp27_guard,
            safety_threshold  = safety_threshold,
            abstain_threshold = safety_abstain_threshold,
            min_train_samples = safety_min_train_samples,
        )

        self._safety_records: List[SafetyDecisionRecord] = []
        self._prev_state_vec: Optional[List[float]] = None
        self._prev_action_id: Optional[int] = None

    def end_of_generation(
        self,
        gen_log:    Dict[str, Any],
        puzzles:    List[Tuple],
        tactic_fns: Dict[str, Any],
        *args: Any,
        **kwargs: Any,
    ) -> Tuple:
        """Override to inject learned safety gate before action is applied."""
        # Build current state vector
        state_vec = [
            float(gen_log.get("accuracy", 0.0)),
            float(gen_log.get("upward_rate", 0.0)),
            float(gen_log.get("downward_rate", 0.0)),
            float(gen_log.get("strategy_entropy", 0.0)),
            float(gen_log.get("best_strategy_prob", 0.0)),
            float(gen_log.get("worst_strategy_prob", 0.0)),
            float(self._generation_count / 100.0),
            float(len(self._safety_dataset) / max(self._safety_dataset.test_fraction * 100, 1)),
        ]

        # Label previous action as safe/unsafe based on accuracy change
        if self._prev_state_vec is not None and self._prev_action_id is not None:
            prev_acc = self._prev_state_vec[0]
            curr_acc = state_vec[0]
            safe     = (curr_acc >= prev_acc - 0.05)   # allow small drops
            rec = ModificationRecord(
                state_before = self._prev_state_vec,
                action_id    = self._prev_action_id,
                state_after  = state_vec,
                safe         = safe,
                generation   = self._generation_count,
            )
            self._safety_dataset.add(rec)
            # Train classifier
            if len(self._safety_dataset) >= self._safety_batch_size:
                batch = self._safety_dataset.sample_batch(self._safety_batch_size)
                features_labels = [
                    (r.to_features(len(SynthesisAction)), int(r.safe))
                    for r in batch
                ]
                self._safety_classifier.train_step(features_labels)

        # Run upstream to get CRLS action
        result = super().end_of_generation(gen_log, puzzles, tactic_fns, *args, **kwargs)

        # Determine proposed action
        proposed_name = gen_log.get("synthesis_action", "RESET_UNIFORM")
        try:
            proposed_action = SynthesisAction[proposed_name]
        except KeyError:
            proposed_action = SynthesisAction.RESET_UNIFORM

        # Build feature vector for safety gate
        action_id = proposed_action.value if hasattr(proposed_action, 'value') else 0
        one_hot   = [0.0] * len(SynthesisAction)
        if 0 <= action_id < len(SynthesisAction):
            one_hot[action_id] = 1.0
        features  = state_vec + one_hot

        # Apply safety gate
        effective_action, source, p_safe = self._learned_guard.apply(
            features     = features,
            dataset_size = len(self._safety_dataset),
            state        = gen_log,
            action       = proposed_action,
            fallback     = self._safety_fallback,
        )
        blocked = (effective_action != proposed_action)

        safety_rec = SafetyDecisionRecord(
            generation             = self._generation_count,
            proposed_action        = proposed_action,
            effective_action       = effective_action,
            decision_source        = source,
            p_safe                 = p_safe,
            blocked                = blocked,
            dataset_size           = len(self._safety_dataset),
            classifier_train_steps = self._safety_classifier.train_steps,
        )
        self._safety_records.append(safety_rec)
        gen_log["wp40_safety_record"] = safety_rec.to_dict()

        # Remember state and action for next generation's label
        self._prev_state_vec = state_vec
        self._prev_action_id = action_id

        return result + (safety_rec,)


# ---------------------------------------------------------------------------
# verify_wp40_exit_criteria — six-criterion verifier
# ---------------------------------------------------------------------------

def verify_wp40_exit_criteria(
    classifier:     SafetyClassifier,
    dataset:        SafetyDataset,
    guard:          LearnedSafetyGuard,
    safety_records: List[SafetyDecisionRecord],
) -> Dict[str, bool]:
    """
    Verify WP40 exit criteria.

    Criteria
    --------
    1. SafetyClassifier produces probabilities ∈ (0, 1).
    2. Classifier training reduces loss over mini-batches.
    3. SafetyDataset stores and retrieves ModificationRecords.
    4. LearnedSafetyGuard defers to fallback when dataset is small.
    5. LearnedSafetyGuard blocks low-p_safe actions when trained.
    6. SafetyDecisionRecord logged each generation.
    """
    results: Dict[str, bool] = {}

    n_actions = classifier.n_actions
    d_state   = classifier.d_in - n_actions

    # 1. Classifier produces valid probabilities
    feat = [0.1] * (d_state) + [1.0] + [0.0] * (n_actions - 1)
    prob = classifier.predict_proba(feat)
    results["SafetyClassifier produces probability in (0,1)"] = (0.0 < prob < 1.0)

    # 2. Training reduces loss (train on artificial safe/unsafe examples)
    fresh_clf = SafetyClassifier(d_state=d_state, n_actions=n_actions, d_hidden=8, seed=1)
    rng = random.Random(0)
    # Safe examples: high state[0] (accuracy)
    # Unsafe: low state[0]
    batch_train = []
    for _ in range(20):
        sv = [rng.uniform(0.7, 1.0)] + [rng.random() for _ in range(d_state - 1)]
        batch_train.append((sv + [1.0] + [0.0] * (n_actions - 1), 1))
    for _ in range(20):
        sv = [rng.uniform(0.0, 0.3)] + [rng.random() for _ in range(d_state - 1)]
        batch_train.append((sv + [0.0, 1.0] + [0.0] * (n_actions - 2), 0))

    rng.shuffle(batch_train)
    loss0 = fresh_clf.train_step(batch_train[:8])
    for _ in range(20):
        fresh_clf.train_step(batch_train)
    loss_final = fresh_clf._loss_history[-1] if fresh_clf._loss_history else loss0
    results["Classifier training reduces loss over mini-batches"] = (loss_final <= loss0 + 0.5)

    # 3. Dataset stores and retrieves
    ds = SafetyDataset(n_actions=n_actions)
    for i in range(5):
        ds.add(ModificationRecord(
            state_before=[float(i)] * d_state,
            action_id=0, state_after=[float(i+1)] * d_state,
            safe=(i % 2 == 0), generation=i,
        ))
    results["SafetyDataset stores and retrieves ModificationRecords"] = (
        len(ds) == 5 and len(ds.sample_batch(3)) == 3
    )

    # 4. Guard defers when dataset is small
    allow, source, _ = guard.check(feat, 0, {}, SynthesisAction.DEMOTE_WORST)

# ---------------------------------------------------------------------------
# ModificationRecord — labelled training example
# ---------------------------------------------------------------------------

@dataclass
class ModificationRecord:
    """
    One labelled training example for the safety classifier.

    Attributes
    ----------
    state_before : List[float]
        State feature vector before the action.
    action_id : int
        Integer ID of the synthesis action applied.
    state_after : List[float]
        State feature vector after the action.
    safe : bool
        True if the modification was retrospectively classified as safe.
    generation : int
    timestamp : float
    """
    state_before: List[float]
    action_id:    int
    state_after:  List[float]
    safe:         bool
    generation:   int
    timestamp:    float = field(default_factory=time.time)

    def to_features(self, n_actions: int) -> List[float]:
        """Build flat feature vector: state_before + action one-hot."""
        one_hot = [0.0] * n_actions
        if 0 <= self.action_id < n_actions:
            one_hot[self.action_id] = 1.0
        return list(self.state_before) + one_hot

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_id":   self.action_id,
            "safe":        self.safe,
            "generation":  self.generation,
        }


# ---------------------------------------------------------------------------
# SafetyDataset — accumulates ModificationRecords
# ---------------------------------------------------------------------------

class SafetyDataset:
    """
    Accumulates ModificationRecord instances and provides batch sampling.

    Parameters
    ----------
    n_actions : int
        Number of possible synthesis actions.
    test_fraction : float
        Fraction of records held out for evaluation (default 0.20).
    """

    def __init__(self, n_actions: int, test_fraction: float = 0.20):
        self.n_actions     = n_actions
        self.test_fraction = test_fraction
        self._records:     List[ModificationRecord] = []
        self._rng          = random.Random(42)

    def add(self, record: ModificationRecord) -> None:
        self._records.append(record)

    def __len__(self) -> int:
        return len(self._records)

    def sample_batch(self, batch_size: int) -> List[ModificationRecord]:
        """Sample a random mini-batch."""
        k = min(batch_size, len(self._records))
        return self._rng.sample(self._records, k)

    def train_test_split(self) -> Tuple[List[ModificationRecord], List[ModificationRecord]]:
        """Return (train, test) lists."""
        records = list(self._records)
        self._rng.shuffle(records)
        n_test  = max(1, int(len(records) * self.test_fraction))
        return records[n_test:], records[:n_test]

    def class_balance(self) -> Dict[str, int]:
        n_safe   = sum(1 for r in self._records if r.safe)
        n_unsafe = len(self._records) - n_safe
        return {"safe": n_safe, "unsafe": n_unsafe}


# ---------------------------------------------------------------------------
# SafetyClassifier — 2-layer MLP: P(safe | state, action)
# ---------------------------------------------------------------------------

class SafetyClassifier:
    """
    2-layer MLP predicting P(safe | state_before, action).

    Architecture:
        input (d_state + n_actions) → hidden (d_hidden) → output (1 sigmoid)

    Training: mini-batch SGD with binary cross-entropy loss.

    Parameters
    ----------
    d_state   : int   State feature dimension.
    n_actions : int   Number of actions (one-hot size).
    d_hidden  : int   Hidden layer width (default 16).
    lr        : float Learning rate (default 0.05).
    l2        : float L2 regularisation (default 1e-4).
    seed      : int
    """

    def __init__(
        self,
        d_state:   int,
        n_actions: int,
        d_hidden:  int   = 16,
        lr:        float = 0.05,
        l2:        float = 1e-4,
        seed:      int   = 0,
    ):
        self.d_in      = d_state + n_actions
        self.d_hidden  = d_hidden
        self.n_actions = n_actions
        self.lr        = lr
        self.l2        = l2
        rng = random.Random(seed)
        sc1 = math.sqrt(2.0 / self.d_in)
        sc2 = math.sqrt(2.0 / d_hidden)
        self._W1: List[List[float]] = _randn_matrix(d_hidden, self.d_in, sc1, rng)
        self._b1: List[float]       = [0.0] * d_hidden
        self._W2: List[float]       = [rng.gauss(0.0, sc2) for _ in range(d_hidden)]
        self._b2: float             = 0.0
        self.train_steps: int       = 0
        self._loss_history: List[float] = []

    def _forward(self, x: List[float]) -> Tuple[List[float], float, float]:
        """Returns (h1_activated, logit, prob)."""
        h1_raw  = _add_vecs(_matvec(self._W1, x), self._b1)
        h1      = [_relu(v) for v in h1_raw]
        logit   = sum(self._W2[j] * h1[j] for j in range(self.d_hidden)) + self._b2
        prob    = 1.0 / (1.0 + math.exp(-max(-500, min(500, logit))))
        return h1, logit, prob

    def predict_proba(self, features: List[float]) -> float:
        """Return P(safe | features) ∈ (0, 1)."""
        _, _, prob = self._forward(features)
        return prob

    def confidence(self, features: List[float]) -> float:
        """Return classifier confidence: |prob - 0.5| * 2 ∈ [0, 1]."""
        prob = self.predict_proba(features)
        return abs(prob - 0.5) * 2.0

    def train_step(self, batch: List[Tuple[List[float], int]]) -> float:
        """
        One mini-batch SGD step.

        Parameters
        ----------
        batch : List[Tuple[features, label]]
            label = 1 (safe) or 0 (unsafe).

        Returns average binary cross-entropy loss.
        """
        if not batch:
            return 0.0
        total_loss = 0.0
        # Accumulate gradients
        dW1 = [[0.0] * self.d_in   for _ in range(self.d_hidden)]
        db1 = [0.0] * self.d_hidden
        dW2 = [0.0] * self.d_hidden
        db2 = 0.0

        for x, y in batch:
            h1, logit, prob = self._forward(x)
            # Binary cross-entropy
            eps = 1e-7
            loss = -(y * math.log(prob + eps) + (1 - y) * math.log(1 - prob + eps))
            total_loss += loss

            # Backprop output layer
            d_logit = prob - y          # dL/d_logit
            for j in range(self.d_hidden):
                dW2[j] += d_logit * h1[j]
            db2 += d_logit

            # Backprop hidden layer
            d_h1 = [d_logit * self._W2[j] for j in range(self.d_hidden)]
            d_h1_raw = [d_h1[j] if h1[j] > 0 else 0.0 for j in range(self.d_hidden)]   # ReLU
            for i in range(self.d_hidden):
                for k in range(self.d_in):
                    dW1[i][k] += d_h1_raw[i] * x[k]
                db1[i] += d_h1_raw[i]

        n = len(batch)
        # SGD update with L2
        for i in range(self.d_hidden):
            for k in range(self.d_in):
                self._W1[i][k] -= self.lr * (dW1[i][k] / n + self.l2 * self._W1[i][k])
            self._b1[i] -= self.lr * (db1[i] / n)
        for j in range(self.d_hidden):
            self._W2[j] -= self.lr * (dW2[j] / n + self.l2 * self._W2[j])
        self._b2 -= self.lr * (db2 / n)

        avg_loss = total_loss / n
        self._loss_history.append(avg_loss)
        self.train_steps += 1
        return avg_loss

    def evaluate(self, records: List[ModificationRecord]) -> Dict[str, float]:
        """Compute accuracy and AUC-ROC approximation on a held-out set."""
        if not records:
            return {"accuracy": 0.0, "n": 0}
        correct = 0
        for rec in records:
            feat = rec.to_features(self.n_actions)
            prob = self.predict_proba(feat)
            pred = int(prob >= 0.5)
            if pred == int(rec.safe):
                correct += 1
        return {
            "accuracy": round(correct / len(records), 4),
            "n":        len(records),
        }


# ---------------------------------------------------------------------------
# LearnedSafetyGuard — drop-in InvariantGuard replacement
# ---------------------------------------------------------------------------

class LearnedSafetyGuard:
    """
    Learned safety gate: uses ``SafetyClassifier`` when trained,
    falls back to WP27's ``InvariantGuard`` otherwise.

    Parameters
    ----------
    classifier : SafetyClassifier
    fallback_guard : InvariantGuard
        WP27 guard to use when classifier is untrained or uncertain.
    safety_threshold : float
        Minimum P(safe) to allow action (default 0.60).
    abstain_threshold : float
        Confidence below which guard defers to fallback (default 0.30).
    min_train_samples : int
        Minimum training examples before classifier is used (default 20).
    """

    def __init__(
        self,
        classifier:        SafetyClassifier,
        fallback_guard:    InvariantGuard,
        safety_threshold:  float = 0.60,
        abstain_threshold: float = 0.30,
        min_train_samples: int   = 20,
    ):
        self.classifier        = classifier
        self.fallback_guard    = fallback_guard
        self.safety_threshold  = safety_threshold
        self.abstain_threshold = abstain_threshold
        self.min_train_samples = min_train_samples

    def check(
        self,
        features:   List[float],
        dataset_size: int,
        state:      Any,
        action:     SynthesisAction,
    ) -> Tuple[bool, str, float]:
        """
        Gate an action.

        Returns (allow: bool, decision_source: str, p_safe: float).

        decision_source ∈ {'learned', 'abstain_fallback', 'untrained_fallback'}
        """
        if dataset_size < self.min_train_samples:
            # Untrained — defer to WP27
            return True, "untrained_fallback", 0.5

        prob       = self.classifier.predict_proba(features)
        confidence = self.classifier.confidence(features)

        if confidence < self.abstain_threshold:
            # Low confidence — defer to WP27
            return True, "abstain_fallback", prob

        allow = (prob >= self.safety_threshold)
        return allow, "learned", prob

    def apply(
        self,
        features:     List[float],
        dataset_size: int,
        state:        Any,
        action:       SynthesisAction,
        fallback:     SynthesisAction = SynthesisAction.RESET_UNIFORM,
    ) -> Tuple[SynthesisAction, str, float]:
        """
        Apply the safety gate.  Returns (effective_action, source, p_safe).
        """
        allow, source, p_safe = self.check(features, dataset_size, state, action)
        if allow:
            return action, source, p_safe
        else:
            logger.info(
                "WP40 safety gate BLOCKED %s (p_safe=%.3f) → %s",
                action.name, p_safe, fallback.name,
            )
            return fallback, source + "_blocked", p_safe



"""
WP40: Learned Safety Model — Neural Gödelian Governor
======================================================

Closes the **brittle-rule gap** in WP27's formal invariant verification.

The gap in WP27
---------------
``InvariantGuard`` (WP27) enforces safety via Hoare-style hard constraints:
invariants are *fixed, hand-written predicates* of the form
"strategy probability must stay above p_floor".  Two problems:

1. **Brittleness**: a hand-written invariant cannot anticipate every unsafe
   state combination.  A configuration that violates no individual invariant
   can still lead to unsafe behaviour through their interaction.

2. **No learning**: the invariant set is static — it cannot improve based on
   the agent's own history of safe and unsafe modifications.

WP40 fix
--------
``ModificationRecord`` — a labelled training example:
    (state_before, action, state_after) → safe: bool.
Generated by observing the outcomes of past synthesis actions.

``SafetyDataset`` — accumulates ``ModificationRecord`` instances and
provides train/test splits and feature engineering.

``SafetyClassifier`` — a lightweight neural network (2-layer MLP, pure
Python) trained to predict P(safe | state_before, action).
  - Features: state_before vector + action one-hot.
  - Output: sigmoid probability ∈ (0, 1).
  - Trained online via mini-batch SGD.
  - Uncertainty estimate: |p - 0.5| as a confidence proxy.

``AbstractionThreshold`` — when classifier confidence < ``abstain_threshold``,
the model *abstains* (defers to WP27's formal invariants rather than
overriding them).  This implements the "defer to human" principle.

``LearnedSafetyGuard`` — drop-in replacement for WP27's ``InvariantGuard``:
  - When the classifier is trained (≥ ``min_train_samples`` examples),
    uses P(safe) to gate actions: block if P(safe) < ``safety_threshold``.
  - Falls back to WP27's ``InvariantGuard`` when confidence is low or
    the classifier is untrained.
  - Adversarial probe: after each action, runs the WP32 spec-gaming
    mutations to check whether the classifier would have passed
    trivially-short solutions.
  - Logs all decisions in ``SafetyDecisionRecord``.

``LearnedSafetyCRLS(TransformerCRLS)`` — 14th layer in the stack:
  - Wraps WP36 ``TransformerCRLS``
  - Maintains a ``SafetyDataset`` and ``SafetyClassifier``
  - Before each synthesis action is applied, gates it through
    ``LearnedSafetyGuard``
  - Trains the classifier online after each generation
  - Amends gen_log with wp40_* fields
  - Returns 14-tuple (13-tuple from WP36, SafetyDecisionRecord)

``verify_wp40_exit_criteria`` — six-criterion verifier.

Theoretical grounding
---------------------
Amodei et al. (2016) "Concrete Problems in AI Safety": learned safety models
that predict the outcomes of actions are more general than hand-written
constraints, especially for complex interaction effects.

Leike et al. (2018) "AI Safety Gridworlds": quantitative safety metrics
derived from observed behaviour are more robust than symbolic rules alone.

Hadfield-Menell et al. (2016) "Cooperative Inverse Reinforcement Learning":
a safety model that can defer to a human when uncertain is safer than one
that always commits to its own prediction.

Good (1965): the centrencephalic system — the Gödelian safety governor —
must be able to *learn* what constitutes a safe self-modification, not
merely enforce a fixed set of rules.  WP40 gives the governor this
learning capability.

Classes
-------
ModificationRecord      (state, action, outcome) training example
SafetyDataset           Labelled dataset with train/test split
SafetyClassifier        2-layer MLP: P(safe | state, action)
LearnedSafetyGuard      Drop-in InvariantGuard replacement
SafetyDecisionRecord    Per-generation safety decision audit
LearnedSafetyCRLS       TransformerCRLS + WP40 learned safety gate
verify_wp40_exit_criteria  Six-criterion verifier
"""


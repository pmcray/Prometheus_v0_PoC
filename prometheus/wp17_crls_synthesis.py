# GoTacticalCRLS  –  full wiring on real Go puzzles
# ---------------------------------------------------------------------------

class GoTacticalCRLS:
    """
    Complete CRLS Strange Loop wired to 9×9 Go tactical puzzles.

    Combines:
    - MetaLearner (Good's synaptic mutation, *optionally frozen* for causal tests)
    - MetaCognitionLayer (Hofstadter's observer)
    - CRLSSynthesiser (WP17: closes the loop)
    - GodelianSafetyGovernor (gates every synthesis action)

    The design separates two sources of learning:
    - **Autonomous** (MetaLearner upward/downward rates applied per-puzzle)
    - **Synthetic**  (CRLSSynthesiser bulk mutations applied once per generation)

    For causal validation, freeze autonomous updates by setting
    ``upward_rate = downward_rate = 0`` at construction.  Then any
    accuracy improvement must come from the CRLS loop.

    Parameters
    ----------
    strategies : list[str]
        Strategy names (must match the tactic functions in the caller).
    upward_rate, downward_rate : float
        Autonomous MetaLearner rates.  Set to 0.0 for causal test mode.
    synthesiser_kwargs : dict
        Extra kwargs forwarded to CRLSSynthesiser.
    """

    def __init__(
        self,
        strategies: List[str],
        upward_rate: float = 0.20,
        downward_rate: float = 0.15,
        synthesiser_kwargs: Optional[Dict[str, Any]] = None,
    ):
        self.meta     = MetaLearner(
            strategies    = strategies,
            upward_rate   = upward_rate,
            downward_rate = downward_rate,
        )
        self.metacog  = MetaCognitionLayer()
        self.governor = GodelianSafetyGovernor()
        self.synth    = CRLSSynthesiser(
            self.meta,
            governor=self.governor,
            **(synthesiser_kwargs or {}),
        )

        self.generation   = 0
        self.acc_history: List[float] = []
        self.gen_log:     List[Dict]  = []

    # ------------------------------------------------------------------
    # Core generation runner
    # ------------------------------------------------------------------

    def run_generation(
        self,
        puzzles: List[Tuple],  # [(GoBoard, player, correct_move), ...]
        tactic_fns: Dict[str, Callable],
        evaluate_fn: Callable,
    ) -> float:
        """
        Play every puzzle; apply autonomous MetaLearner updates per puzzle.

        Returns accuracy for this generation.
        """
        # Close the causal window from the previous synthesis
        if self.acc_history:
            self.synth.record_next_generation_acc(
                self._evaluate_batch(puzzles, tactic_fns, evaluate_fn, update=False)
            )

        # Now play with updates
        correct = 0
        for i, (board, player, correct_move) in enumerate(puzzles):
            strategy = self.meta.select_strategy()
            move     = tactic_fns[strategy](board, player)

            # Fallback to random if tactic returns nothing legal
            if move is None or not board.is_legal_move(move[0], move[1], player):
                legal = board.get_legal_moves(player)
                move  = legal[0] if legal else (-1, -1)
                strategy = list(tactic_fns.keys())[-1]  # random_legal assumed last

            success = evaluate_fn(board, move, correct_move, player)
            if success:
                self.meta.update_on_success(strategy)
                correct += 1
            else:
                self.meta.update_on_failure(strategy)
                self.metacog.observe_failure(FailureEpisode(
                    turn             = i,
                    failure_type     = FailureType.STRATEGIC_ERROR,
                    context          = {"strategy": strategy, "board_size": board.size},
                    action_taken     = strategy,
                    expected_outcome = 1.0,
                    actual_outcome   = 0.0,
                    causal_diagnosis = f"strategy '{strategy}' failed",
                ))

        acc = correct / len(puzzles)
        self.acc_history.append(acc)
        return acc

    def end_of_generation(self, regime: str = "") -> SynthesisRecord:
        """
        Run the synthesis phase: meta-level observes → synthesiser acts.

        Must be called once per generation *after* run_generation().
        """
        acc_now  = self.acc_history[-1]
        acc_prev = self.acc_history[-2] if len(self.acc_history) >= 2 else None

        record = self.synth.synthesise(
            generation      = self.generation,
            acc_this_gen    = acc_now,
            acc_prev_gen    = acc_prev,
            pattern_summary = self.metacog.get_pattern_summary(),
        )

        self.gen_log.append({
            "generation":   self.generation,
            "regime":       regime,
            "acc":          acc_now,
            "action":       record.action.value,
            "trigger":      record.trigger,
            "safety":       record.safety_status,
            "probs_before": record.before_probs,
            "probs_after":  record.after_probs,
            "upward_rate":  record.after_upward,
        })

        self.generation += 1
        return record

    def get_full_report(self) -> Dict[str, Any]:
        """Return complete experiment report."""
        return {
            "generations":     len(self.acc_history),
            "accuracy_history": self.acc_history,
            "final_accuracy":   self.acc_history[-1] if self.acc_history else None,
            "meta_statistics":  self.meta.get_statistics(),
            "synthesis_summary": self.synth.get_summary(),
            "safety_statistics": self.governor.get_safety_statistics(),
            "generation_log":   self.gen_log,
        }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _evaluate_batch(
        self,
        puzzles: List[Tuple],
        tactic_fns: Dict[str, Callable],
        evaluate_fn: Callable,
        update: bool = False,
    ) -> float:
        """Evaluate accuracy without synthesis (used for causal window close)."""
        correct = 0
        for board, player, correct_move in puzzles:
            strategy = self.meta.select_strategy()
            move     = tactic_fns[strategy](board, player)
            if move is None or not board.is_legal_move(move[0], move[1], player):
                legal = board.get_legal_moves(player)
                move  = legal[0] if legal else (-1, -1)
                strategy = list(tactic_fns.keys())[-1]
            success = evaluate_fn(board, move, correct_move, player)
            if update:
                if success:
                    self.meta.update_on_success(strategy)
                else:
                    self.meta.update_on_failure(strategy)
            if success:
                correct += 1
        return correct / len(puzzles)


# ---------------------------------------------------------------------------
# Exit-criteria verifier (mirrors v0.114 pattern)
# ---------------------------------------------------------------------------

def verify_wp17_exit_criteria(crls: GoTacticalCRLS) -> Dict[str, bool]:
    """
    Verify WP17 exit criteria.

    Criteria
    --------
    loop_fires         At least one synthesis action was applied
    causal_confirmed   At least one action causally improved accuracy
    within_3_gens      Causal confirmation achieved within first 3 generations
    meta_level_active  MetaCognitionLayer observed at least one failure
    safety_gated       Every synthesis proposal was evaluated by the governor
    no_unsafe_applied  No PROVABLY_UNSAFE action was applied

    Returns
    -------
    dict mapping criterion name → bool
    """
    report = crls.get_full_report()
    synth  = report["synthesis_summary"]
    safety = report["safety_statistics"]

    applied   = [r for r in crls.synth.records
                 if r.action != SynthesisAction.NO_ACTION]
    confirmed = [r for r in applied if r.causal_confirmed()]

    # Earliest generation with a confirmed causal improvement
    first_confirm_gen = (
        min(r.generation for r in confirmed) if confirmed else None
    )

    criteria = {
        "loop_fires":        len(applied) > 0,
        "causal_confirmed":  len(confirmed) > 0,
        "within_3_gens":     (first_confirm_gen is not None
                              and first_confirm_gen <= 2),
        "meta_level_active": (report["meta_statistics"]["attempt_count"] > 0
                              and len(crls.metacog.failure_history) > 0),
        "safety_gated":      safety["total_decisions"] > 0,
        "no_unsafe_applied": all(
            r.safety_status != SafetyStatus.PROVABLY_UNSAFE.value
            for r in crls.synth.records
            if r.action != SynthesisAction.NO_ACTION
        ),
    }

    logger.info("WP17 exit criteria: %s", criteria)
    return criteria

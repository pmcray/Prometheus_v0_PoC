"""
WP17: CRLS Synthesis Closure
=============================

Closes the fourth quadrant of the CRLS Strange Loop so that the correction
generated by the meta-level actually mutates the object-level MetaLearner,
and the subsequent generation's accuracy confirms the causal effect.

The gap in v0.114
-----------------
``SelfCorrectionEngine.apply_correction()`` returns a modified dict that nothing
reads; the MetaLearner is never touched.  The loop *observes* and *generates*
but never *synthesises* — Hofstadter's fourth beat is missing.

WP17 fix
--------
``CRLSSynthesiser`` holds a live reference to the ``MetaLearner`` and executes
four concrete synthesis actions that directly mutate strategy probabilities:

  DEMOTE_WORST   – halve the probability of the worst-performing strategy
  PROMOTE_BEST   – double the probability of the best-performing strategy
  RESET_UNIFORM  – reset to uniform prior (escape local optima)
  BOOST_UPWARD   – increase the upward mutation rate itself (meta-meta level)

The key to distinguishing CRLS synthesis from the MetaLearner's own autonomous
updates: the test harness sets ``upward_rate = downward_rate = 0`` (frozen
autonomous updates) and relies entirely on the CRLS loop for learning.  Any
accuracy improvement in generation N+1 is therefore causally attributable to
the synthesis action taken at the end of generation N.

Theoretical grounding
---------------------
Hofstadter (GEB, 1979): "In a strange loop … we unexpectedly find ourselves
back where we started."  The loop closes here: the meta-level's correction
changes the MetaLearner whose outputs the meta-level will observe next.

Good (1965): "An ultraintelligent machine … could design even better machines."
The BOOST_UPWARD action demonstrates meta-meta-learning — the machine improves
its own improvement rate.

Classes
-------
SynthesisAction     Enum of the four concrete synthesis operations
SynthesisRecord     Dataclass: one synthesis event (action, before/after probs,
                    generation, safety status)
CRLSSynthesiser     The synthesis engine: takes MetaLearner + pattern summary,
                    proposes a safe action, applies it, records the event
GoTacticalCRLS      Full CRLS loop wired to 9×9 Go tactical puzzles, using the
                    real GoBoard and the existing MetaLearner / MetaCognitionLayer
"""

from __future__ import annotations

import copy
import logging
import math
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Dict, List, Optional, Tuple

from prometheus.meta_learner import MetaLearner
